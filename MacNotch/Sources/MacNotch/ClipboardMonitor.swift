import AppKit
import Foundation

/// Keeps a history of copied text, links, images and files.
///
/// Items that apps mark as concealed or transient (passwords from 1Password, Keychain and so on)
/// are never recorded. Text, links and files are saved between launches; images are kept as PNGs.
final class ClipboardMonitor: ObservableObject {
    static let shared = ClipboardMonitor()

    struct Item: Identifiable, Codable, Equatable {
        enum Kind: String, Codable { case text, link, image, file }

        var id = UUID()
        var kind: Kind
        var text: String?
        var imageFile: String?
        var filePaths: [String]?
        var date: Date
        var sourceBundleID: String?
        var pinned = false

        var title: String {
            switch kind {
            case .text, .link: return text ?? ""
            case .image: return "Image"
            case .file:
                let names = (filePaths ?? []).map { ($0 as NSString).lastPathComponent }
                return names.count > 1 ? "\(names[0]) + \(names.count - 1) more" : names.first ?? "File"
            }
        }
    }

    @Published private(set) var items: [Item] = []
    /// Briefly set after an item is copied back, so its card can confirm it.
    @Published private(set) var lastCopiedID: UUID?

    private let pasteboard = NSPasteboard.general
    private var changeCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    private static var directory: URL { AppSettings.storageDirectory.appendingPathComponent("Clipboard", isDirectory: true) }
    private static var historyFile: URL { directory.appendingPathComponent("history.json") }

    func setRunning(_ running: Bool) {
        if running, timer == nil {
            load()
            changeCount = pasteboard.changeCount
            let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
            RunLoop.main.add(timer, forMode: .common)
            self.timer = timer
        } else if !running {
            timer?.invalidate()
            timer = nil
        }
    }

    private func poll() {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        guard let types = pasteboard.types,
              !types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }),
              let item = capture(types: types) else { return }
        insert(item)
    }

    private func capture(types: [NSPasteboard.PasteboardType]) -> Item? {
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return Item(kind: .file, filePaths: urls.map(\.path), date: Date(), sourceBundleID: source)
        }
        if let text = pasteboard.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines), !text.isEmpty {
            let clipped = String(text.prefix(20_000))
            let isLink = URL(string: clipped).map { ["http", "https"].contains($0.scheme?.lowercased() ?? "") } ?? false
            return Item(kind: isLink ? .link : .text, text: clipped, date: Date(), sourceBundleID: source)
        }
        if types.contains(.png) || types.contains(.tiff), let image = NSImage(pasteboard: pasteboard),
           let file = Self.saveImage(image) {
            return Item(kind: .image, imageFile: file, date: Date(), sourceBundleID: source)
        }
        return nil
    }

    private func insert(_ item: Item) {
        // Copying something already in the list moves it to the top instead of duplicating it.
        if let existing = items.firstIndex(where: { $0.kind == item.kind && $0.text == item.text && $0.filePaths == item.filePaths && item.kind != .image }) {
            var moved = items.remove(at: existing)
            moved.date = item.date
            items.insert(moved, at: 0)
        } else {
            items.insert(item, at: 0)
        }
        trim()
        save()
    }

    private func trim() {
        let limit = max(5, AppSettings.shared.clipboardLimit)
        var unpinned = 0
        items = items.filter { item in
            if item.pinned { return true }
            unpinned += 1
            if unpinned <= limit { return true }
            Self.deleteImage(of: item)
            return false
        }
    }

    // MARK: Actions

    func copy(_ item: Item) {
        pasteboard.clearContents()
        switch item.kind {
        case .text, .link:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            if let file = item.imageFile, let image = NSImage(contentsOf: Self.directory.appendingPathComponent(file)) {
                pasteboard.writeObjects([image])
            }
        case .file:
            pasteboard.writeObjects((item.filePaths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        }
        changeCount = pasteboard.changeCount
        if let index = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
        lastCopiedID = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            if self?.lastCopiedID == item.id { self?.lastCopiedID = nil }
        }
    }

    func togglePin(_ item: Item) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        save()
    }

    func remove(_ item: Item) {
        Self.deleteImage(of: item)
        items.removeAll { $0.id == item.id }
        save()
    }

    func clear() {
        items.filter { !$0.pinned }.forEach(Self.deleteImage)
        items.removeAll { !$0.pinned }
        save()
    }

    func image(for item: Item) -> NSImage? {
        item.imageFile.flatMap { NSImage(contentsOf: Self.directory.appendingPathComponent($0)) }
    }

    // MARK: Storage

    private func load() {
        guard items.isEmpty, let data = try? Data(contentsOf: Self.historyFile),
              let saved = try? JSONDecoder().decode([Item].self, from: data) else { return }
        items = saved
    }

    private func save() {
        try? FileManager.default.createDirectory(at: Self.directory, withIntermediateDirectories: true)
        try? JSONEncoder().encode(items).write(to: Self.historyFile, options: .atomic)
    }

    private static func saveImage(_ image: NSImage) -> String? {
        try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        // Keep previews small: at most 800 pixels on the long side.
        let size = image.size
        let scale = min(1, 800 / max(size.width, size.height, 1))
        let target = NSSize(width: size.width * scale, height: size.height * scale)
        let resized = NSImage(size: target, flipped: false) { rect in
            image.draw(in: rect)
            return true
        }
        guard let tiff = resized.tiffRepresentation, let bitmap = NSBitmapImageRep(data: tiff),
              let png = bitmap.representation(using: .png, properties: [:]) else { return nil }
        let name = "clip-\(UUID().uuidString).png"
        return (try? png.write(to: directory.appendingPathComponent(name))) != nil ? name : nil
    }

    private static func deleteImage(of item: Item) {
        guard let file = item.imageFile else { return }
        try? FileManager.default.removeItem(at: directory.appendingPathComponent(file))
    }
}
